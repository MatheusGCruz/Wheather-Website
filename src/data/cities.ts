export const CITIES: CityEntry[] = entries.map(
  ([city, state, country, slug, query, countryCode]) => ({
    city,
    state,
    country,
    slug: slug ?? city.toLowerCase().replace(/\s+/g, '-'),
    query: query ?? city,
    countryCode: countryCode ?? COUNTRY_CODES[country],
  }),
);

export function findCityBySlug(slug: string): CityEntry | undefined {
  return CITIES.find((entry) => entry.slug === slug);
}

export function getCountries(): string[] {
  return [...new Set(CITIES.map((entry) => entry.country))].sort();
}

export function getStates(country: string): string[] {
  return [
    ...new Set(
      CITIES.filter((entry) => entry.country === country).map((entry) => entry.state),
    ),
  ].sort();
}

export function getCities(country: string, state: string): CityEntry[] {
  return CITIES.filter(
    (entry) => entry.country === country && entry.state === state,
  ).sort((a, b) => a.city.localeCompare(b.city));
}
